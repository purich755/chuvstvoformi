// Точки задаются вручную, кривая — Катмулл—Ром → кубические Безье. Координаты округлены (иначе гидратация расходится).

type P = [number, number];

export function smooth(points: P[], closed = false): string {
  const p = points;
  const r = (v: number) => Math.round(v * 10) / 10;
  let d = `M${r(p[0][0])} ${r(p[0][1])}`;
  const n = p.length;
  for (let i = 0; i < (closed ? n : n - 1); i++) {
    const p0 = i > 0 ? p[i - 1] : closed ? p[n - 1] : p[i];
    const p1 = p[i];
    const p2 = p[(i + 1) % n];
    const p3 = closed || i + 2 < n ? p[(i + 2) % n] : p2;
    const c1: P = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2: P = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${r(c1[0])} ${r(c1[1])} ${r(c2[0])} ${r(c2[1])} ${r(p2[0])} ${r(p2[1])}`;
  }
  return d;
}

